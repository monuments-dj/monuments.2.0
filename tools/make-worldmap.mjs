// Builds src/components/WorldMap.astro from Natural Earth 110m land (public
// domain) with a plain equirectangular projection, so pin lat/lon math is exact.
import fs from 'fs';
const W = 1000, H = 500;
const px = (lon, lat) => [((lon + 180) / 360 * W), ((90 - lat) / 180 * H)];
const land = JSON.parse(fs.readFileSync('/tmp/land.json', 'utf8'));
let d = '';
for (const f of land.features) {
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const poly of polys) {
    for (const ring of poly) {
      d += 'M' + ring.map(([lon, lat]) => px(lon, lat).map(n => n.toFixed(1)).join(',')).join('L') + 'Z';
    }
  }
}
// DJ's places (2026-07-11). img optional - fills in as he supplies them.
const PINS = [
  ['Boise, Idaho', 43.62, -116.2],
  ["Coeur d'Alene, Idaho", 47.68, -116.78],
  ['Utah', 40.76, -111.89],
  ['Los Angeles', 34.05, -118.24],
  ['San Diego', 32.72, -117.16],
  ['San Jose', 37.34, -121.89],
  ['San Francisco', 37.77, -122.42],
  ['Modesto', 37.64, -120.99],
  ['Oregon', 45.52, -122.68],
  ['New York', 40.71, -74.0],
  ['North Carolina', 35.23, -80.84],
  ['Atlanta', 33.75, -84.39],
  ['Florida', 25.76, -80.19],
  ['Mexico', 19.43, -99.13],
  ['Ecuador', -0.18, -78.47],
  ['Portugal', 38.72, -9.14],
  ['Jordan', 31.95, 35.93],
  ['Dubai', 25.2, 55.27],
  ['Uganda', 0.35, 32.58],
  ['Nepal', 27.7, 85.32],
];
const pins = PINS.map(([name, lat, lon]) => {
  const [x, y] = px(lon, lat);
  return `      <g class="pin" transform="translate(${x.toFixed(1)},${y.toFixed(1)})" data-place="${name}"><circle class="hit" r="12"/><circle class="dot" r="4.5"/><circle class="ring" r="4.5"/></g>`;
}).join('\n');

const component = `---
// WorldMap.astro · "\\\\ The map" - places DJ has worked. GENERATED by
// tools/make-worldmap.mjs from Natural Earth 110m land (public domain),
// plain equirectangular projection so pin lat/lon placement is exact.
// Edit pins in the generator and re-run; hover shows the place label.
---
<section class="wmap">
  <div class="wrap">
    <div class="bar">
      <span class="mono"><b>\\ The map</b> · places I've worked</span>
      <span class="mono wm-dim">Hover the pins</span>
    </div>
    <div class="wm-stage">
      <svg viewBox="60 40 880 420" role="img" aria-label="World map of places DJ has worked">
        <path class="land" d="${d}"/>
${pins}
      </svg>
      <div class="wm-tip mono" id="wmTip" hidden></div>
    </div>
  </div>
</section>

<style>
.wmap{background:var(--ink,#161514);padding:9vh 0 8vh;color:var(--paper,#F5F3EF)}
.wmap .bar{display:flex;justify-content:space-between;align-items:baseline;gap:16px;flex-wrap:wrap;padding-bottom:14px;border-bottom:1px solid rgba(245,243,239,.16);margin-bottom:28px}
.wmap .bar .mono b{color:var(--spark,#EFA1AD)}
.wm-dim{color:#8f8d88}
.wm-stage{position:relative}
.wmap svg{width:100%;height:auto;display:block}
.land{fill:#3a3835;stroke:none}
.pin .hit{fill:transparent;pointer-events:all}
.pin .dot{fill:#E0311A;pointer-events:none}
.pin .ring{fill:none;stroke:#E0311A;stroke-width:1.4;opacity:.8;transform-origin:center;animation:wmPulse 2.6s ease-out infinite;pointer-events:none}
.pin:hover .dot{fill:#F5F3EF}
@keyframes wmPulse{0%{transform:scale(1);opacity:.8}70%{transform:scale(2.6);opacity:0}100%{transform:scale(2.6);opacity:0}}
.pin{cursor:pointer}
.wm-tip{position:absolute;z-index:3;pointer-events:none;background:#F5F3EF;color:#161514;font-size:10.5px;letter-spacing:.09em;text-transform:uppercase;padding:7px 12px;border-radius:6px;white-space:nowrap;transform:translate(-50%,-140%)}
@media (prefers-reduced-motion:reduce){.pin .ring{animation:none;opacity:0}}
</style>

<script is:inline>
(function(){
  var stage=document.querySelector('.wm-stage'),tip=document.getElementById('wmTip');
  if(!stage||!tip)return;
  stage.querySelectorAll('.pin').forEach(function(p){
    p.addEventListener('mouseenter',function(){
      var r=p.getBoundingClientRect(),s=stage.getBoundingClientRect();
      tip.textContent=p.getAttribute('data-place');
      tip.style.left=(r.left-s.left+r.width/2)+'px';
      tip.style.top=(r.top-s.top)+'px';
      tip.hidden=false;
    });
    p.addEventListener('mouseleave',function(){tip.hidden=true;});
  });
})();
</script>
`;
fs.writeFileSync('src/components/WorldMap.astro', component);
console.log('WorldMap.astro written · path bytes:', d.length, '· pins:', PINS.length);
